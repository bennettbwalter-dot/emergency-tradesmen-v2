CREATE OR REPLACE FUNCTION public.next_social_publish_at(
  base_time timestamptz,
  local_publish_time time,
  timezone_name text
)
RETURNS timestamptz
LANGUAGE plpgsql
STABLE
SET search_path = ''
AS $$
DECLARE
  local_base timestamp;
  local_target timestamp;
BEGIN
  local_base := base_time AT TIME ZONE timezone_name;
  local_target := date_trunc('day', local_base) + local_publish_time;
  IF local_target <= local_base THEN
    local_target := local_target + interval '1 day';
  END IF;
  RETURN local_target AT TIME ZONE timezone_name;
END;
$$;

CREATE OR REPLACE FUNCTION public.enqueue_social_campaign_for_post()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  settings_row public.social_automation_settings%ROWTYPE;
  campaign_id uuid;
  post_market text;
  publish_time timestamptz;
  base_url text;
BEGIN
  IF NEW.published IS DISTINCT FROM true OR NEW.published_at IS NULL THEN
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE'
     AND OLD.published IS TRUE
     AND OLD.published_at IS NOT DISTINCT FROM NEW.published_at THEN
    RETURN NEW;
  END IF;

  SELECT * INTO settings_row
  FROM public.social_automation_settings
  WHERE id = 'default';

  IF NOT FOUND OR settings_row.enabled IS NOT TRUE THEN
    RETURN NEW;
  END IF;

  post_market := CASE WHEN NEW.slug LIKE '%-us' THEN 'US' ELSE 'GB' END;
  base_url := CASE
    WHEN post_market = 'US' THEN 'https://emergencycontractors.net/blog/'
    ELSE 'https://emergencytradesmen.net/blog/'
  END;
  publish_time := public.next_social_publish_at(
    NEW.published_at,
    settings_row.daily_publish_time,
    settings_row.schedule_timezone
  );

  INSERT INTO public.social_campaigns (
    source_post_id,
    market,
    state,
    idempotency_key,
    safety_review_required,
    requires_approval,
    scheduled_at
  )
  VALUES (
    NEW.id,
    post_market,
    'detected',
    'blog:' || NEW.slug || ':social-v1',
    false,
    settings_row.approval_mode = 'always',
    publish_time
  )
  ON CONFLICT (idempotency_key) DO UPDATE SET
    scheduled_at = COALESCE(public.social_campaigns.scheduled_at, EXCLUDED.scheduled_at),
    updated_at = timezone('utc', now())
  RETURNING id INTO campaign_id;

  INSERT INTO public.social_publications (
    campaign_id,
    account_id,
    status,
    destination_url,
    media_url,
    scheduled_at,
    schedule_timezone
  )
  SELECT
    campaign_id,
    account.id,
    'draft',
    base_url || NEW.slug,
    NEW.cover_image,
    publish_time,
    settings_row.schedule_timezone
  FROM public.social_accounts AS account
  WHERE account.market = post_market
    AND account.enabled
  ON CONFLICT (campaign_id, account_id) DO NOTHING;

  INSERT INTO public.social_automation_events (campaign_id, event_type, event_data)
  VALUES (
    campaign_id,
    'blog_detected',
    jsonb_build_object(
      'post_id', NEW.id,
      'slug', NEW.slug,
      'published_at', NEW.published_at,
      'scheduled_at', publish_time
    )
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS enqueue_social_campaign_after_publish ON public.posts;
CREATE TRIGGER enqueue_social_campaign_after_publish
AFTER INSERT OR UPDATE OF published, published_at ON public.posts
FOR EACH ROW
EXECUTE FUNCTION public.enqueue_social_campaign_for_post();

