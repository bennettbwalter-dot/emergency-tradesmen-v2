-- Reliable blog-to-social queue. Content generation and provider publishing run
-- in the server-side worker; this migration owns detection, idempotency, state,
-- scheduling defaults, audit events, and approval/failure alerts.

ALTER TABLE public.social_accounts
  DROP CONSTRAINT IF EXISTS social_accounts_platform_check;

ALTER TABLE public.social_accounts
  ADD CONSTRAINT social_accounts_platform_check
  CHECK (platform IN ('facebook', 'instagram', 'tiktok', 'pinterest', 'linkedin', 'x')),
  ADD COLUMN IF NOT EXISTS enabled boolean NOT NULL DEFAULT true;

ALTER TABLE public.social_campaigns
  ADD COLUMN IF NOT EXISTS trend_status text NOT NULL DEFAULT 'pending'
    CHECK (trend_status IN ('pending', 'running', 'complete', 'skipped', 'failed')),
  ADD COLUMN IF NOT EXISTS quality_status text NOT NULL DEFAULT 'pending'
    CHECK (quality_status IN ('pending', 'passed', 'failed')),
  ADD COLUMN IF NOT EXISTS quality_score integer
    CHECK (quality_score IS NULL OR quality_score BETWEEN 0 AND 50),
  ADD COLUMN IF NOT EXISTS requires_approval boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS last_error text,
  ADD COLUMN IF NOT EXISTS next_attempt_at timestamptz,
  ADD COLUMN IF NOT EXISTS processing_started_at timestamptz,
  ADD COLUMN IF NOT EXISTS processing_completed_at timestamptz;

ALTER TABLE public.social_publications
  ADD COLUMN IF NOT EXISTS content_hash text,
  ADD COLUMN IF NOT EXISTS quality_score integer
    CHECK (quality_score IS NULL OR quality_score BETWEEN 0 AND 50),
  ADD COLUMN IF NOT EXISTS quality_report jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS generated_at timestamptz,
  ADD COLUMN IF NOT EXISTS reviewed_at timestamptz,
  ADD COLUMN IF NOT EXISTS approved_at timestamptz;

CREATE TABLE IF NOT EXISTS public.social_automation_settings (
  id text PRIMARY KEY DEFAULT 'default' CHECK (id = 'default'),
  enabled boolean NOT NULL DEFAULT true,
  daily_publish_time time NOT NULL DEFAULT '18:30:00',
  schedule_timezone text NOT NULL DEFAULT 'Europe/London',
  minimum_quality_score integer NOT NULL DEFAULT 35
    CHECK (minimum_quality_score BETWEEN 0 AND 50),
  approval_mode text NOT NULL DEFAULT 'safety_only'
    CHECK (approval_mode IN ('always', 'safety_only', 'none')),
  trend_research_enabled boolean NOT NULL DEFAULT true,
  max_publish_attempts integer NOT NULL DEFAULT 3
    CHECK (max_publish_attempts BETWEEN 1 AND 10),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

INSERT INTO public.social_automation_settings (id)
VALUES ('default')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.social_automation_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  campaign_id uuid REFERENCES public.social_campaigns(id) ON DELETE CASCADE,
  publication_id uuid REFERENCES public.social_publications(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  event_data jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now())
);

CREATE TABLE IF NOT EXISTS public.social_automation_alerts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  campaign_id uuid REFERENCES public.social_campaigns(id) ON DELETE CASCADE,
  publication_id uuid REFERENCES public.social_publications(id) ON DELETE CASCADE,
  severity text NOT NULL CHECK (severity IN ('info', 'warning', 'error')),
  alert_type text NOT NULL,
  message text NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'acknowledged', 'resolved')),
  dedupe_key text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  resolved_at timestamptz
);

CREATE INDEX IF NOT EXISTS social_campaigns_processing_idx
  ON public.social_campaigns (state, next_attempt_at, created_at);
CREATE INDEX IF NOT EXISTS social_events_campaign_idx
  ON public.social_automation_events (campaign_id, created_at DESC);
CREATE INDEX IF NOT EXISTS social_alerts_open_idx
  ON public.social_automation_alerts (status, severity, created_at DESC)
  WHERE status = 'open';
CREATE UNIQUE INDEX IF NOT EXISTS social_publications_content_hash_idx
  ON public.social_publications (account_id, content_hash)
  WHERE content_hash IS NOT NULL
    AND status NOT IN ('failed', 'cancelled');

