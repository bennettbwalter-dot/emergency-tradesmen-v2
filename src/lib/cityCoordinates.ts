/**
 * Calculate the distance between two coordinates using the Haversine formula
 * Returns distance in kilometers
 */
export function calculateDistance(
    lat1: number,
    lng1: number,
    lat2: number,
    lng2: number
): number {
    const R = 6371; // Earth's radius in kilometers
    const dLat = toRad(lat2 - lat1);
    const dLng = toRad(lng2 - lng1);

    const a =
        Math.sin(dLat / 2) * Math.sin(dLat / 2) +
        Math.cos(toRad(lat1)) *
        Math.cos(toRad(lat2)) *
        Math.sin(dLng / 2) *
        Math.sin(dLng / 2);

    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const distance = R * c;

    return distance;
}

function toRad(degrees: number): number {
    return degrees * (Math.PI / 180);
}

/**
 * Find the nearest city from a given coordinate
 * Uses UK coordinates for GB, US coordinates for US
 * Returns the city name and distance
 */
export function findNearestCity(lat: number, lng: number, countryCode: string = 'GB'): {
    city: string;
    distance: number;
} {
    const coordsToSearch = countryCode === 'US' ? usCityCoordinates : cityCoordinates;
    let nearestCity = "";
    let minDistance = Infinity;

    for (const [city, coords] of Object.entries(coordsToSearch)) {
        const distance = calculateDistance(lat, lng, coords.lat, coords.lng);
        if (distance < minDistance) {
            minDistance = distance;
            nearestCity = city;
        }
    }

    return { city: nearestCity, distance: minDistance };
}
