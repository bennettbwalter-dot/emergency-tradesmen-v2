    const post = await fetchPost('smart-leak-detection-gb');
    if (!post) {
        console.log('Post not found');
        return;
    }

    console.log('Old cover_image:', post.cover_image);
    const newCoverImage = '/images/blog/generated/smart-leaky-hero.png';
    
